"use client";

import { useEffect, useRef, useState, type ReactNode } from "react";
import { AnimatePresence, motion, useReducedMotion } from "motion/react";
import { ArrowUpRight, RotateCcw, SendHorizontal, Square, X } from "lucide-react";
import { conversationId, identityHeaders, startNewConversation } from "@/lib/assistant/identity";
import type { Link } from "@/lib/assistant/knowledge";
import { scrollToId } from "@/components/providers/smooth-scroll";
import { OPEN_PROJECT } from "@/components/projects/projects";
import { SiteTour, TOUR_ENDED, startTour } from "@/components/tour/site-tour";
import { cn } from "@/lib/utils";
import { ArcOrb } from "./arc-orb";

const OPEN_EVENT = "md:open-assistant";
export function openAssistant() {
  window.dispatchEvent(new Event(OPEN_EVENT));
}

type Status = "thinking" | "streaming" | "done" | "error";
/**
 * Something Arc can do on the page: scroll to a section, play the guided tour of the whole site, download the resume,
 * or open a link (GitHub, LinkedIn, email…). `confirm` means Arc is asking first; otherwise the visitor agreed and it should happen now.
 */
type ArcAction = { kind: "navigate" | "download" | "open" | "tour"; key: string; label: string; confirm: boolean; href?: string; section?: string };
type BotMsg = {
  id: number;
  role: "bot";
  text: string;
  links: Link[];
  status: Status;
  /** shown under the answer, e.g. that generation was stopped */
  note?: string;
  action?: ArcAction;
  /** the visitor's answer to this message's offer, once they've clicked Yes or No */
  choice?: "yes" | "no";
};
type Msg = { id: number; role: "user"; text: string } | BotMsg;
type ArcEvent =
  | { type: "context" }
  | { type: "token"; text: string }
  | { type: "action"; action: ArcAction }
  | { type: "done"; links: Link[] }
  | { type: "error"; message: string };

const MAX_QUESTION = 500;

/** Renders **bold**, blank-line paragraphs and line breaks (Arc's lists are "- " lines). */
function rich(text: string): ReactNode[] {
  return text.split(/\n{2,}/).map((para, pi) => (
    <p key={pi} className={cn("whitespace-pre-line", pi && "mt-2.5")}>
      {para.split(/(\*\*[^*]+\*\*)/g).map((part, i) =>
        part.startsWith("**") && part.endsWith("**") ? (
          <strong key={i} className="font-semibold text-fg">{part.slice(2, -2)}</strong>
        ) : (
          <span key={i}>{part}</span>
        )
      )}
    </p>
  ));
}

/**
 * Arc: Mehul's generative portfolio assistant.
 * Questions go to /api/arc, which streams an answer generated by Arc's language model from retrieved portfolio
 * facts and the conversation so far. Every answer comes from the model; if it's unreachable, the chat says so.
 */
export function Assistant() {
  const reduce = useReducedMotion();
  const [open, setOpen] = useState(false);
  const [input, setInput] = useState("");
  const [pulse, setPulse] = useState(0);
  const [msgs, setMsgs] = useState<Msg[]>([]);
  const asked = useRef<string[]>([]);
  const askedIdx = useRef(-1);
  const nextId = useRef(1);
  const controller = useRef<AbortController | null>(null);
  const restored = useRef(false);
  const scroller = useRef<HTMLDivElement>(null);
  const inputRef = useRef<HTMLInputElement>(null);

  useEffect(() => {
    const onOpen = () => setOpen(true);
    const onKey = (e: KeyboardEvent) => {
      if (e.key === "Escape") setOpen(false);
      // Ctrl/Cmd + M toggles Arc from anywhere on the page
      if ((e.ctrlKey || e.metaKey) && e.key.toLowerCase() === "m") {
        e.preventDefault();
        setOpen((o) => !o);
      }
    };
    // back from the guided tour, unless the visitor took over by scrolling (then they're reading)
    const onTourEnded = (e: Event) => { if ((e as CustomEvent<{ reopen: boolean }>).detail?.reopen) setOpen(true); };
    window.addEventListener(OPEN_EVENT, onOpen);
    window.addEventListener("keydown", onKey);
    window.addEventListener(TOUR_ENDED, onTourEnded);
    return () => {
      window.removeEventListener(OPEN_EVENT, onOpen);
      window.removeEventListener("keydown", onKey);
      window.removeEventListener(TOUR_ENDED, onTourEnded);
    };
  }, []);

  useEffect(() => {
    if (!open) return;
    setTimeout(() => inputRef.current?.focus(), 120);
    // the first time the chat opens, bring back this tab's conversation (it's stored by Arc's server)
    if (restored.current) return;
    restored.current = true;
    (async () => {
      try {
        const res = await fetch(`/api/arc?conversation=${conversationId()}`, { headers: await identityHeaders() });
        if (!res.ok) return;
        const { messages } = (await res.json()) as { messages: { role: "user" | "assistant"; content: string }[] };
        if (!messages?.length) return;
        setMsgs((current) => current.length ? current : messages.map((m) => m.role === "user"
          ? { id: nextId.current++, role: "user" as const, text: m.content }
          : { id: nextId.current++, role: "bot" as const, text: m.content, links: [], status: "done" as const }));
      } catch {}
    })();
  }, [open]);

  useEffect(() => {
    const el = scroller.current;
    if (el) el.scrollTop = el.scrollHeight;
  }, [msgs, open]);

  const patch = (id: number, fn: (m: BotMsg) => BotMsg) =>
    setMsgs((all) => all.map((x) => (x.id === id && x.role === "bot" ? fn(x) : x)));

  const busy = msgs.some((m) => m.role === "bot" && (m.status === "thinking" || m.status === "streaming"));

  const offline = (botId: number) => patch(botId, (x) => ({
    ...x, status: "error",
    text: "Arc is offline right now, so I can't answer. Please try again in a little while, or reach Mehul through the Contact section.",
  }));

  /** `performed`: the visitor clicked Yes and the action already ran, so don't run it again when Arc confirms */
  const ask = async (q: string, performed = false) => {
    const question = q.trim().slice(0, MAX_QUESTION);
    if (!question || busy) return;
    asked.current = [question, ...asked.current].slice(0, 20);
    askedIdx.current = -1;
    const botId = nextId.current + 1;
    const turn: Msg[] = [
      { id: nextId.current++, role: "user", text: question },
      { id: nextId.current++, role: "bot", text: "", links: [], status: "thinking" },
    ];
    setMsgs((m) => [...m, ...turn].slice(-40));
    setInput("");

    const ac = new AbortController();
    controller.current = ac;
    try {
      const res = await fetch("/api/arc", {
        method: "POST",
        headers: { "Content-Type": "application/json", ...(await identityHeaders()) },
        body: JSON.stringify({ question, conversation_id: conversationId() }),
        signal: ac.signal,
      });
      if (res.status === 503) return offline(botId);
      if (!res.ok || !res.body) {
        const { error } = await res.json().catch(() => ({ error: "Arc couldn't answer that. Please try again." }));
        return patch(botId, (x) => ({ ...x, text: error, status: "error" }));
      }
      let agreed: ArcAction | null = null; // the visitor typed "yes" to an offer: do it once Arc has replied
      const reader = res.body.getReader();
      const decoder = new TextDecoder();
      let buffer = "";
      for (;;) {
        const { value, done } = await reader.read();
        if (done) break;
        buffer += decoder.decode(value, { stream: true });
        const lines = buffer.split("\n");
        buffer = lines.pop() ?? "";
        for (const line of lines) {
          if (!line.trim()) continue;
          const ev = JSON.parse(line) as ArcEvent;
          if (ev.type === "action") {
            patch(botId, (x) => ({ ...x, action: ev.action }));
            if (!ev.action.confirm && !performed) agreed = ev.action;
          } else if (ev.type === "token") patch(botId, (x) => ({ ...x, text: x.text + ev.text, status: "streaming" }));
          else if (ev.type === "done") patch(botId, (x) => ({ ...x, text: x.text.trim(), links: ev.links ?? [], status: "done" }));
          else if (ev.type === "error") patch(botId, (x) => ({ ...x, text: ev.message, status: "error" }));
        }
      }
      patch(botId, (x) => (x.status === "thinking" || x.status === "streaming" ? { ...x, status: "done" } : x));
      // let the visitor read Arc's reply for a moment, then do it
      if (agreed) { const a = agreed; setTimeout(() => perform(a), 700); }
    } catch {
      if (ac.signal.aborted) {
        patch(botId, (x) => ({ ...x, status: "done", note: x.text ? "Stopped." : undefined, text: x.text || "Stopped." }));
      } else {
        offline(botId);
      }
    } finally {
      controller.current = null;
    }
  };

  const stop = () => controller.current?.abort();

  const newChat = () => {
    stop();
    startNewConversation();
    setMsgs([]);
    inputRef.current?.focus();
  };

  const follow = (l: Link) => {
    if (l.section?.startsWith("project-")) {
      scrollToId("work");
      window.dispatchEvent(new CustomEvent(OPEN_PROJECT, { detail: l.section.slice("project-".length) }));
      if (window.matchMedia("(max-width: 640px)").matches) setOpen(false);
    } else if (l.section) {
      scrollToId(l.section);
      if (window.matchMedia("(max-width: 640px)").matches) setOpen(false);
    } else if (l.href) {
      const a = document.createElement("a");
      a.href = l.href;
      if (l.href.endsWith(".pdf")) a.download = "";
      else if (!/^(mailto|tel):/.test(l.href)) { a.target = "_blank"; a.rel = "noreferrer"; } // email and calls open their app, not a tab
      a.click();
    }
  };

  const perform = (a: ArcAction) => {
    if (a.kind !== "tour") return follow({ label: a.label, section: a.section, href: a.href });
    // Arc minimises so the whole page is visible, and comes back when the tour ends (see TOUR_ENDED)
    setOpen(false);
    startTour();
  };

  /** Yes runs the action inside the click, so the browser allows the new tab or download; then Arc confirms. */
  const choose = (m: BotMsg, yes: boolean) => {
    if (!m.action || m.choice || busy) return;
    patch(m.id, (x) => ({ ...x, choice: yes ? "yes" : "no" }));
    if (yes) perform(m.action);
    void ask(yes ? "Yes" : "No", yes);
  };

  const thinking = msgs.some((m) => m.role === "bot" && m.status === "thinking");
  const streaming = msgs.some((m) => m.role === "bot" && m.status === "streaming");
  const orbState = thinking || streaming ? "thinking" : input ? "listening" : "idle";
  const empty = msgs.length === 0;

  return (
    <>
      <SiteTour />
      {/* launcher */}
      <motion.button
        type="button"
        onClick={() => setOpen((o) => !o)}
        aria-expanded={open}
        aria-controls="md-assistant"
        aria-label={open ? "Close Arc" : "Ask Arc (Ctrl + M)"}
        data-cursor={open ? "close arc" : "ask arc · ctrl m"}
        initial={reduce ? false : { opacity: 0, y: 16 }}
        animate={{ opacity: 1, y: 0 }}
        transition={{ delay: 2.4, duration: 0.6 }}
        className="screen fixed bottom-[calc(1.25rem+env(safe-area-inset-bottom,0px))] right-4 z-50 flex items-center gap-2.5 rounded-full border border-line-strong bg-panel/90 py-1.5 pl-1.5 pr-4 text-[13px] font-medium text-fg shadow-[0_18px_40px_-18px_rgb(0_0_0/0.8)] backdrop-blur-md transition-colors hover:border-signal sm:right-6 md:hidden"
      >
        <span className="relative grid size-8 place-items-center overflow-hidden rounded-full bg-ink">
          {open ? <X className="size-4 text-signal" aria-hidden /> : <ArcOrb size={32} state="idle" />}
        </span>
        <span className="hidden sm:inline">{open ? "Close" : "Ask Arc"}</span>
        {!open ? <kbd className="hidden rounded border border-line px-1.5 py-0.5 font-mono text-[10px] text-dim sm:inline">Ctrl M</kbd> : null}
      </motion.button>

      <AnimatePresence>
        {open ? (
          <motion.section
            id="md-assistant"
            role="dialog"
            aria-label="Arc, Mehul's portfolio assistant"
            initial={reduce ? { opacity: 0 } : { opacity: 0, y: 20, scale: 0.96 }}
            animate={{ opacity: 1, y: 0, scale: 1 }}
            exit={reduce ? { opacity: 0 } : { opacity: 0, y: 16, scale: 0.97 }}
            transition={{ duration: 0.28, ease: [0.16, 1, 0.3, 1] }}
            style={{ transformOrigin: "100% 100%" }}
            className="screen fixed bottom-[calc(4.75rem+env(safe-area-inset-bottom,0px))] right-4 z-50 flex h-[min(600px,calc(100svh-7rem))] md:bottom-6 md:h-[min(640px,calc(100svh-6rem))] w-[calc(100vw-2rem)] flex-col overflow-hidden rounded-2xl border border-line-strong bg-panel/95 shadow-[0_40px_80px_-30px_rgb(0_0_0/0.9)] backdrop-blur-xl sm:right-6 sm:w-[410px]"
          >
            {/* header */}
            <header className="flex items-center justify-between gap-3 border-b border-line px-4 py-2.5">
              <div className="flex items-center gap-2.5">
                <ArcOrb size={34} state={orbState} pulse={pulse} />
                <div className="flex flex-col leading-tight">
                  <span className="font-display text-[15px] font-semibold tracking-tight text-fg [font-stretch:110%]">Arc</span>
                  <span className="font-mono text-[10.5px] text-dim">
                    {thinking ? "thinking…" : streaming ? "answering…" : "Mehul's AI assistant"}
                  </span>
                </div>
              </div>
              <div className="flex items-center gap-1">
                {!empty ? (
                  <button type="button" onClick={newChat} aria-label="New chat" title="New chat" className="grid size-8 place-items-center rounded-md text-soft transition-colors hover:bg-ink-2 hover:text-fg">
                    <RotateCcw className="size-4" aria-hidden />
                  </button>
                ) : null}
                <button type="button" onClick={() => setOpen(false)} aria-label="Close Arc" className="grid size-8 place-items-center rounded-md text-soft transition-colors hover:bg-ink-2 hover:text-fg">
                  <X className="size-4" aria-hidden />
                </button>
              </div>
            </header>

            {/* conversation */}
            <div ref={scroller} data-lenis-prevent className="flex flex-1 flex-col gap-5 overflow-y-auto px-4 py-4" aria-live="polite">
              {empty ? (
                <div className="m-auto flex max-w-[30ch] flex-col items-center gap-4 text-center">
                  <ArcOrb size={150} state={orbState} pulse={pulse} />
                  <div className="flex flex-col gap-2">
                    <p className="font-display text-2xl font-semibold tracking-tight text-fg [font-stretch:112%]">Hi, I&apos;m Arc.</p>
                    <p className="text-[14px] leading-relaxed text-soft">
                      Ask me anything about Mehul: his work, his projects, what he knows, or how to reach him.
                    </p>
                  </div>
                  <p className="font-mono text-[10.5px] text-dim">open-weight model · answers only from this site · Built with Llama</p>
                </div>
              ) : null}

              {msgs.map((m) =>
                m.role === "user" ? (
                  <motion.div
                    key={m.id}
                    initial={reduce ? false : { opacity: 0, y: 8 }}
                    animate={{ opacity: 1, y: 0 }}
                    className="max-w-[85%] self-end whitespace-pre-line rounded-2xl rounded-br-md bg-signal/15 px-3.5 py-2 text-[14px] leading-relaxed text-fg"
                  >
                    {m.text}
                  </motion.div>
                ) : (
                  <BotBubble key={m.id} m={m} busy={busy} onFollow={follow} onChoose={(yes) => choose(m, yes)} />
                )
              )}
            </div>

            {/* input */}
            <form onSubmit={(e) => { e.preventDefault(); void ask(input); }} className="flex items-center gap-2 border-t border-line p-3">
              <label htmlFor="md-assistant-input" className="sr-only">Ask Arc a question</label>
              <input
                id="md-assistant-input"
                ref={inputRef}
                value={input}
                onChange={(e) => { setInput(e.target.value); setPulse((p) => p + 1); }}
                onKeyDown={(e) => {
                  if (e.key === "ArrowUp" && asked.current.length) {
                    e.preventDefault();
                    askedIdx.current = Math.min(asked.current.length - 1, askedIdx.current + 1);
                    setInput(asked.current[askedIdx.current]);
                  } else if (e.key === "ArrowDown" && askedIdx.current >= 0) {
                    e.preventDefault();
                    askedIdx.current -= 1;
                    setInput(askedIdx.current >= 0 ? asked.current[askedIdx.current] : "");
                  }
                }}
                maxLength={MAX_QUESTION}
                autoComplete="off"
                placeholder="Ask Arc anything about Mehul…"
                className="h-10 flex-1 rounded-lg border border-line bg-ink-2 px-3 text-[14px] text-fg outline-none placeholder:text-dim focus:border-signal/60"
              />
              {busy ? (
                <button type="button" onClick={stop} aria-label="Stop generating" title="Stop" className="grid size-10 place-items-center rounded-lg border border-line-strong text-fg transition-colors hover:border-signal">
                  <Square className="size-3.5 fill-current" aria-hidden />
                </button>
              ) : (
                <button type="submit" disabled={!input.trim()} aria-label="Send" className="grid size-10 place-items-center rounded-lg bg-signal text-on-signal transition-opacity disabled:opacity-40">
                  <SendHorizontal className="size-4" aria-hidden />
                </button>
              )}
            </form>
          </motion.section>
        ) : null}
      </AnimatePresence>
    </>
  );
}

function BotBubble({ m, busy, onFollow, onChoose }: {
  m: BotMsg; busy: boolean; onFollow: (l: Link) => void; onChoose: (yes: boolean) => void;
}) {
  const reduce = useReducedMotion();
  const thinking = m.status === "thinking";

  return (
    <div className="flex max-w-[94%] flex-col gap-2 self-start">
      {thinking ? (
        <div className="flex w-fit items-center gap-2.5 rounded-2xl rounded-bl-md border border-line bg-ink-2 px-3.5 py-2.5 text-[13px] text-soft">
          <span className="flex items-center gap-1" aria-hidden>
            {[0, 1, 2].map((i) => (
              <motion.span
                key={i}
                className="size-1.5 rounded-full bg-signal"
                animate={reduce ? undefined : { opacity: [0.3, 1, 0.3], y: [0, -3, 0] }}
                transition={{ duration: 1, repeat: Infinity, delay: i * 0.15, ease: "easeInOut" }}
              />
            ))}
          </span>
          Thinking
        </div>
      ) : (
        <div className={cn(
          "rounded-2xl rounded-bl-md border px-3.5 py-2.5 text-[14px] leading-relaxed",
          m.status === "error" ? "border-red-400/40 bg-red-400/5 text-soft" : "border-line bg-ink-2 text-soft",
        )}>
          {rich(m.text)}
          {m.status === "streaming" ? <span className="ml-0.5 inline-block h-[1em] w-[0.45em] translate-y-[2px] bg-signal animate-[blink_1s_steps(1)_infinite]" /> : null}
        </div>
      )}

      {m.note ? <p className="pl-1 font-mono text-[10.5px] text-dim">{m.note}</p> : null}

      {/* an offer: the visitor answers with a click */}
      {m.status === "done" && m.action?.confirm ? (
        m.choice ? (
          <p className="pl-1 font-mono text-[10.5px] text-dim">You chose {m.choice === "yes" ? "Yes" : "No"}</p>
        ) : (
          <div className="flex items-center gap-2">
            <button type="button" disabled={busy} onClick={() => onChoose(true)} className="rounded-full bg-signal px-4 py-1.5 text-[12.5px] font-medium text-on-signal transition-opacity hover:opacity-90 disabled:opacity-40">
              Yes
            </button>
            <button type="button" disabled={busy} onClick={() => onChoose(false)} className="rounded-full border border-line-strong px-4 py-1.5 text-[12.5px] text-fg transition-colors hover:border-signal disabled:opacity-40">
              No
            </button>
          </div>
        )
      ) : null}

      {/* done after a typed "yes": a fallback in case the browser blocked the new tab or download */}
      {m.status === "done" && m.action && !m.action.confirm && m.action.href ? (
        <button type="button" onClick={() => onFollow({ label: m.action!.label, href: m.action!.href })} className="flex w-fit items-center gap-1 rounded-full border border-signal/40 px-2.5 py-1 text-[12px] text-signal transition-colors hover:bg-signal/10">
          {m.action.kind === "download" ? "Download didn't start? Download resume" : `Didn't open? Open ${m.action.label}`}
          <ArrowUpRight className="size-3" aria-hidden />
        </button>
      ) : null}

      {m.status === "done" && !m.action && m.links.length ? (
        <div className="flex flex-wrap items-center gap-1.5">
          {m.links.map((l) => (
            <button key={l.label} type="button" onClick={() => onFollow(l)} className="flex items-center gap-1 rounded-full border border-signal/40 px-2.5 py-1 text-[12px] text-signal transition-colors hover:bg-signal/10">
              {l.label}
              <ArrowUpRight className="size-3" aria-hidden />
            </button>
          ))}
        </div>
      ) : null}
    </div>
  );
}
