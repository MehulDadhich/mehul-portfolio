"use client";

import { useCallback, useEffect, useRef, useState } from "react";
import dynamic from "next/dynamic";
import { gsap } from "gsap";
import { ScrollTrigger } from "gsap/ScrollTrigger";
import { SplitText } from "gsap/SplitText";
import { useGSAP } from "@gsap/react";
import { ArrowDown, Mail } from "lucide-react";
import { certifications, gmailCompose, profile, projects, roadguardMetrics } from "@/lib/content";
import { scrollToId } from "@/components/providers/smooth-scroll";
import { GithubIcon, LinkedinIcon } from "@/components/shared/brand-icons";
import { DiffusionName } from "./diffusion-name";
import type { CoreState } from "./core-scene";

gsap.registerPlugin(useGSAP, ScrollTrigger, SplitText);

const CoreScene = dynamic(() => import("./core-scene"), { ssr: false });

const hasWebGL = () => {
  try {
    const c = document.createElement("canvas");
    return !!(c.getContext("webgl2") || c.getContext("webgl"));
  } catch {
    return false;
  }
};

/** The readout under the name. Every figure comes from content.ts (months: experience.period, Jan – Jul 2026). */
const latency = roadguardMetrics[0].value.match(/^([\d.]+)\s*(.*)$/)!;
const STATS = [
  { value: 6, decimals: 0, unit: "", label: "Months at Infrax.ai" },
  { value: projects.length, decimals: 0, unit: "", label: "Systems built" },
  { value: parseFloat(latency[1]), decimals: 1, unit: latency[2], label: "RoadGuard frame p50" },
  { value: certifications.length, decimals: 0, unit: "", label: "Certifications" },
];

/**
 * The hero is a pinned stage around a 3D core (see core-scene). Intro: the core grows out of nothing, the name is
 * generated by diffusion (the real h1, sampled out of noise), then the line, the actions and the readout arrive.
 * Scroll: the words clear, the camera dives into the core, and a veil in the machine view's colour hands over to
 * the RoadGuard chapter.
 */
export function Hero() {
  const root = useRef<HTMLElement>(null);
  const state = useRef<CoreState>({ scroll: 0, intro: 0, still: false });
  const [gl, setGl] = useState<boolean | null>(null);
  const [ready, setReady] = useState(false);
  const [play, setPlay] = useState(false);
  const [active, setActive] = useState(true);
  const onReady = useCallback(() => setReady(true), []);

  // the intro is the opening of the page, so a reload starts at the top rather than mid-scroll
  useEffect(() => {
    if ("scrollRestoration" in history) history.scrollRestoration = "manual";
    window.scrollTo(0, 0);
    const id = requestAnimationFrame(() => setGl(hasWebGL()));
    return () => cancelAnimationFrame(id);
  }, []);

  // stop rendering the core once the hero has scrolled away
  useEffect(() => {
    const io = new IntersectionObserver(([e]) => setActive(e.isIntersecting));
    if (root.current) io.observe(root.current);
    return () => io.disconnect();
  }, []);

  // if the scene is slow (or fails), don't hold the page hostage
  useEffect(() => {
    const id = setTimeout(() => setReady(true), 5000);
    return () => clearTimeout(id);
  }, []);

  const { contextSafe } = useGSAP(
    () => {
      if (!ready && gl !== false) return;
      const mm = gsap.matchMedia();
      mm.add({ motion: "(prefers-reduced-motion: no-preference)", reduce: "(prefers-reduced-motion: reduce)" }, (ctx) => {
        if (ctx.conditions?.reduce || gl === false) {
          Object.assign(state.current, { intro: 1, still: true });
          gsap.set("[data-hero-in], [data-hero-fade], [data-hero-split]", { autoAlpha: 1 });
          setPlay(true);
          return;
        }

        // ---- intro, part one: the core grows in and the name starts generating ----
        gsap.set("[data-hero-in]", { autoAlpha: 1 });
        gsap.set("[data-hero-fade]", { autoAlpha: 0, y: 12 });
        gsap.set("[data-hud-corner]", { scale: 0 });
        gsap.set("[data-hero-split]", { autoAlpha: 0 });
        const tl = gsap.timeline({ defaults: { ease: "expo.out" } });
        tl.fromTo("[data-hero-glow]", { autoAlpha: 0 }, { autoAlpha: 1, duration: 1.8, ease: "power2.out" }, 0)
          .to(state.current, { intro: 1, duration: 2.4 }, 0.1)
          .call(() => setPlay(true), [], 0.6)
          .to("[data-hud-corner]", { scale: 1, duration: 0.7, stagger: 0.06, ease: "back.out(1.6)" }, 0.9);

        // ---- scroll: the words clear, the camera dives into the core, the machine view takes the frame ----
        const out = gsap.timeline({
          scrollTrigger: {
            trigger: root.current,
            start: "top top",
            end: "bottom bottom",
            scrub: true,
            onUpdate: (self) => { state.current.scroll = self.progress; },
          },
        });
        out.to("[data-hero-copy]", { autoAlpha: 0, y: -70, filter: "blur(6px)", ease: "power1.in", duration: 0.3 }, 0)
          .to("[data-hero-stats]", { autoAlpha: 0, y: 40, ease: "power1.in", duration: 0.22 }, 0.04)
          .to("[data-hud]", { autoAlpha: 0, duration: 0.2 }, 0.05)
          .fromTo("[data-hero-through]", { autoAlpha: 0, scale: 0.94 }, { autoAlpha: 1, scale: 1, duration: 0.15, ease: "power2.out" }, 0.5)
          .to("[data-hero-through]", { autoAlpha: 0, duration: 0.1 }, 0.82)
          .to("[data-hero-veil]", { autoAlpha: 1, duration: 0.14, ease: "none" }, 0.86);

        return () => { tl.kill(); };
      });
    },
    { scope: root, dependencies: [ready, gl] }
  );

  // ---- intro, part two: once the name exists, the line rises, the actions and the readout arrive ----
  const onGenerated = useCallback(() => contextSafe(() => {
    if (window.matchMedia("(prefers-reduced-motion: reduce)").matches || gl === false) return;
    const split = SplitText.create("[data-hero-split]", { type: "lines,words", mask: "lines" });
    const tl = gsap.timeline({ defaults: { ease: "expo.out" } })
      .set("[data-hero-split]", { autoAlpha: 1 }, 0)
      .from(split.words, { yPercent: 110, duration: 1.1, stagger: 0.035 }, 0)
      .to("[data-hero-fade]", { autoAlpha: 1, y: 0, duration: 0.8, stagger: 0.08 }, 0.3);
    // the readout counts up to its figures
    root.current?.querySelectorAll<HTMLElement>("[data-count]").forEach((el, i) => {
      const to = parseFloat(el.dataset.count!), dec = Number(el.dataset.decimals || 0), o = { v: 0 };
      tl.to(o, { v: to, duration: 1.6, ease: "power3.out", onUpdate: () => { el.textContent = o.v.toFixed(dec); } }, 0.5 + i * 0.08);
    });
  })(), [contextSafe, gl]);

  return (
    <section id="top" ref={root} aria-labelledby="hero-title" className="relative h-[100svh] motion-safe:h-[230svh]">
      <noscript>
        <style>{`[data-name-h1],[data-hero-in],[data-hero-fade],[data-hero-split]{visibility:visible!important}`}</style>
      </noscript>
      <div className="sticky top-0 h-[100svh] overflow-hidden bg-ink">
        {/* a low vermilion glow under the core, so the stage isn't a flat black */}
        <div data-hero-glow className="pointer-events-none absolute inset-0 bg-[radial-gradient(ellipse_55%_45%_at_50%_48%,color-mix(in_srgb,var(--signal)_14%,transparent),transparent_70%)]" aria-hidden />

        <div className="pointer-events-none absolute inset-0">
          {gl ? <CoreScene state={state} active={active} onReady={onReady} /> : null}
        </div>

        {/* keeps the words readable over the core: a soft dark centre and a darker floor */}
        <div className="pointer-events-none absolute inset-0 bg-[radial-gradient(ellipse_50%_38%_at_50%_50%,rgb(12_12_11/0.45),transparent_70%),linear-gradient(to_top,rgb(12_12_11/0.85),transparent_38%)]" aria-hidden />

        {/* viewfinder: corner brackets and a hint */}
        <div data-hud className="pointer-events-none absolute inset-3 sm:inset-5" aria-hidden>
          {["left-0 top-16 border-l border-t", "right-0 top-16 border-r border-t", "left-0 bottom-0 border-l border-b", "right-0 bottom-0 border-r border-b"].map((c, i) => (
            <span key={c} data-hud-corner className={`absolute size-5 border-fg/40 ${c}`} style={{ transformOrigin: `${i % 2 ? "100%" : "0%"} ${i < 2 ? "0%" : "100%"}` }} />
          ))}
          <p data-hero-fade className="invisible absolute right-0 top-20 hidden text-right font-mono text-[10.5px] leading-relaxed tracking-[0.12em] text-soft uppercase md:block">
            Hover the name to disturb it
            <br />
            Scroll to dive in <span className="inline-block motion-safe:animate-bounce">↓</span>
          </p>
        </div>

        {/* the words, centred over the core */}
        <div data-hero-copy className="pointer-events-none absolute inset-x-0 top-0 bottom-[12.5rem] flex items-center justify-center sm:bottom-[8rem]">
          <div data-hero-in className="invisible shell flex flex-col items-center text-center">
            <p data-hero-fade className="label mb-10 flex items-center gap-2 text-fg sm:mb-12">
              <span className="relative flex size-2" aria-hidden>
                <span className="absolute inset-0 rounded-full bg-ok opacity-60 motion-safe:animate-ping motion-safe:[animation-duration:2.4s]" />
                <span className="relative size-2 rounded-full bg-ok" />
              </span>
              Open to AI/ML roles · {profile.location}
            </p>
            <div className="pointer-events-auto text-left">
              <DiffusionName play={play} onGenerated={onGenerated}>
                <h1
                  id="hero-title"
                  data-name-h1
                  className="serif invisible text-[clamp(3.6rem,1rem+9vw,9.5rem)] leading-[0.86] tracking-[-0.035em] [text-shadow:0_4px_40px_rgb(12_12_11/0.7)] motion-reduce:visible"
                >
                  <span data-line className="block">Mehul</span>
                  <span data-line className="block pl-[0.75em] italic">Dadhich</span>
                  <span className="sr-only">, {profile.role}</span>
                </h1>
              </DiffusionName>
            </div>
            <p data-hero-split className="serif invisible mt-6 max-w-[34ch] text-[clamp(1.15rem,0.9rem+1vw,1.6rem)] leading-[1.15] tracking-[-0.01em] sm:mt-8">
              AI/ML engineer. I build AI systems and take them <em className="text-signal">past the notebook.</em>
            </p>
            <div data-hero-fade className="pointer-events-auto invisible mt-6 flex flex-wrap items-center justify-center gap-1.5 sm:gap-2">
              <button
                type="button"
                onClick={() => scrollToId("featured")}
                className="group flex h-11 items-center gap-1.5 rounded-full bg-fg pl-3.5 pr-3 text-[13.5px] font-medium text-ink transition-transform duration-300 hover:scale-[1.03] active:scale-[0.98] sm:h-12 sm:gap-2 sm:pl-5 sm:pr-4 sm:text-[15px]"
              >
                See what the model sees
                <ArrowDown className="size-4 transition-transform duration-300 group-hover:translate-y-0.5" aria-hidden />
              </button>
              <a href={gmailCompose()} target="_blank" rel="noreferrer" aria-label="Email (opens Gmail)" className="grid size-11 place-items-center rounded-full border border-line-strong bg-ink/40 backdrop-blur-sm transition-colors hover:border-fg sm:size-12">
                <Mail className="size-4" aria-hidden />
              </a>
              <a href={profile.github} target="_blank" rel="noreferrer" aria-label="GitHub" className="grid size-11 place-items-center rounded-full border border-line-strong bg-ink/40 backdrop-blur-sm transition-colors hover:border-fg sm:size-12">
                <GithubIcon className="size-4" />
              </a>
              <a href={profile.linkedin} target="_blank" rel="noreferrer" aria-label="LinkedIn" className="grid size-11 place-items-center rounded-full border border-line-strong bg-ink/40 backdrop-blur-sm transition-colors hover:border-fg sm:size-12">
                <LinkedinIcon className="size-4" />
              </a>
            </div>
          </div>
        </div>

        {/* the readout: four measured figures along the floor of the stage */}
        <div data-hero-stats className="pointer-events-none absolute inset-x-0 bottom-0 pb-[calc(env(safe-area-inset-bottom,0px)+4.75rem)] sm:pb-[max(1.75rem,env(safe-area-inset-bottom))]">
          <dl data-hero-fade className="invisible shell grid max-w-[880px] grid-cols-2 gap-x-6 gap-y-4 border-t border-line pt-5 sm:grid-cols-4">
            {STATS.map((s) => (
              <div key={s.label} className="flex flex-col-reverse items-center">
                <dt className="label mt-2">{s.label}</dt>
                <dd className="num text-[clamp(1.6rem,1.1rem+1.8vw,2.6rem)] leading-none tracking-[-0.05em] text-fg">
                  <span data-count={s.value} data-decimals={s.decimals}>{s.value.toFixed(s.decimals)}</span>
                  {s.unit ? <span className="ml-[0.22em] text-[0.52em] font-normal tracking-normal text-soft">{s.unit}</span> : null}
                </dd>
              </div>
            ))}
          </dl>
        </div>

        {/* mid-dive caption, then the veil that hands over to the next chapter */}
        <p data-hero-through className="pointer-events-none invisible absolute inset-x-0 bottom-[16%] text-center font-mono text-[12px] tracking-[0.3em] text-fg uppercase" aria-hidden>
          Entering the model
        </p>
        <div data-hero-veil className="pointer-events-none invisible absolute inset-0 bg-[#05070f]" aria-hidden />
      </div>
    </section>
  );
}
