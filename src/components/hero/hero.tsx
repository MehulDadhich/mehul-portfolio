"use client";

import { useCallback, useEffect, useRef, useState } from "react";
import dynamic from "next/dynamic";
import { gsap } from "gsap";
import { ScrollTrigger } from "gsap/ScrollTrigger";
import { SplitText } from "gsap/SplitText";
import { useGSAP } from "@gsap/react";
import { ArrowDown, Mail } from "lucide-react";
import { gmailCompose, profile } from "@/lib/content";
import { scrollToId } from "@/components/providers/smooth-scroll";
import { GithubIcon, LinkedinIcon } from "@/components/shared/brand-icons";
import { DiffusionName } from "./diffusion-name";
import type { HeroState, NameLine } from "./lens-scene";

gsap.registerPlugin(useGSAP, ScrollTrigger, SplitText);

const LensScene = dynamic(() => import("./lens-scene"), { ssr: false });

/** A regular polygon clip-path: the aperture's iris, `r` as a fraction of the larger viewport side. */
function iris(el: HTMLElement, r: number, rot: number, sides = 8) {
  const { width: w, height: h } = el.getBoundingClientRect();
  const R = Math.max(w, h) * r;
  const pts = Array.from({ length: sides }, (_, i) => {
    const a = rot + (i / sides) * Math.PI * 2;
    return `${(w / 2 + Math.cos(a) * R).toFixed(1)}px ${(h / 2 + Math.sin(a) * R).toFixed(1)}px`;
  });
  el.style.clipPath = `polygon(${pts.join(",")})`;
}

const hasWebGL = () => {
  try {
    const c = document.createElement("canvas");
    return !!(c.getContext("webgl2") || c.getContext("webgl"));
  } catch {
    return false;
  }
};

/**
 * The hero is a pinned stage. Intro: an aperture irises open and pulls focus; the name is generated by
 * diffusion (the real h1, sampled out of noise); a detection pass locks onto it; then the lens drops in.
 * The name sits *behind* the transparent WebGL canvas, so outside the lens you read the type, and through
 * the lens you see the machine view's copy of it, drawn exactly over it.
 * Scroll: the overlay clears, the lens rises to the camera until it fills the frame, and a veil in the
 * machine view's colour hands over to the RoadGuard chapter.
 */
export function Hero() {
  const root = useRef<HTMLElement>(null);
  const stage = useRef<HTMLDivElement>(null);
  const state = useRef<HeroState>({ scroll: 0, lens: 0, nameOn: 0, name: null, still: false });
  const [gl, setGl] = useState<boolean | null>(null);
  const [ready, setReady] = useState(false);
  const [play, setPlay] = useState(false);
  const [active, setActive] = useState(true);
  const onReady = useCallback(() => setReady(true), []);

  // the intro is the opening of the page, so a reload starts at the top rather than mid-scroll
  useEffect(() => {
    if ("scrollRestoration" in history) history.scrollRestoration = "manual";
    window.scrollTo(0, 0);
    if (process.env.NODE_ENV !== "production") (window as unknown as { __hero: HeroState }).__hero = state.current;
    const id = requestAnimationFrame(() => setGl(hasWebGL()));
    return () => cancelAnimationFrame(id);
  }, []);

  // stop rendering the lens once the hero has scrolled away
  useEffect(() => {
    const io = new IntersectionObserver(([e]) => setActive(e.isIntersecting));
    if (root.current) io.observe(root.current);
    return () => io.disconnect();
  }, []);

  // if the scene is slow (or fails), don't hold the page hostage
  useEffect(() => {
    const id = setTimeout(() => setReady(true), 5000);
    return () => clearTimeout(id);
  }, []);

  /** Measure the DOM name, line by line, in canvas pixels, for the machine view's copy. */
  const measure = useCallback(() => {
    const st = stage.current;
    const h1 = st?.querySelector("h1");
    if (!st || !h1) return;
    const s = st.getBoundingClientRect();
    const r = h1.getBoundingClientRect();
    const ctx = document.createElement("canvas").getContext("2d")!;
    const lines: NameLine[] = [...h1.querySelectorAll<HTMLElement>("[data-line]")].map((el) => {
      const cs = getComputedStyle(el);
      const lr = el.getBoundingClientRect();
      const font = `${cs.fontStyle} ${cs.fontWeight} ${cs.fontSize} ${cs.fontFamily}`;
      ctx.font = font;
      (ctx as CanvasRenderingContext2D & { letterSpacing?: string }).letterSpacing = cs.letterSpacing === "normal" ? "0px" : cs.letterSpacing;
      const m = ctx.measureText(el.textContent || "");
      const fa = m.fontBoundingBoxAscent ?? m.actualBoundingBoxAscent;
      const fd = m.fontBoundingBoxDescent ?? m.actualBoundingBoxDescent;
      const letterSpacing = cs.letterSpacing === "normal" ? "0px" : cs.letterSpacing;
      // the text starts after the line's padding (the italic second line is indented)
      const left = lr.left - s.left + parseFloat(cs.paddingLeft || "0");
      return { text: el.textContent || "", font, letterSpacing, left, baseline: lr.top - s.top + (lr.height - (fa + fd)) / 2 + fa };
    });
    state.current.name = { x: r.left - s.left, y: r.top - s.top, w: r.width, h: r.height, lines, version: (state.current.name?.version ?? 0) + 1 };
  }, []);

  useEffect(() => {
    let t: ReturnType<typeof setTimeout>;
    const onResize = () => { clearTimeout(t); t = setTimeout(measure, 150); };
    window.addEventListener("resize", onResize);
    return () => { window.removeEventListener("resize", onResize); clearTimeout(t); };
  }, [measure]);

  const { contextSafe } = useGSAP(
    () => {
      if (!ready && gl !== false) return;
      const mm = gsap.matchMedia();
      mm.add({ motion: "(prefers-reduced-motion: no-preference)", reduce: "(prefers-reduced-motion: reduce)" }, (ctx) => {
        const st = stage.current!;
        if (ctx.conditions?.reduce || gl === false) {
          Object.assign(state.current, { lens: 1, nameOn: 1, still: true });
          gsap.set("[data-hero-in], [data-hero-fade]", { autoAlpha: 1 });
          st.style.clipPath = "none";
          setPlay(true);
          return;
        }

        // ---- intro, part one: the aperture opens and the name starts generating ----
        const ap = { r: 0.004, rot: 0 };
        const blur = { px: 18 };
        gsap.set("[data-hero-in]", { autoAlpha: 1 });
        gsap.set("[data-hero-fade]", { autoAlpha: 0, y: 12 });
        gsap.set("[data-hud-corner]", { scale: 0 });
        gsap.set("[data-hero-split]", { autoAlpha: 0 });
        const tl = gsap.timeline({ defaults: { ease: "expo.out" } });
        tl.to(ap, { r: 0.03, duration: 0.5, ease: "power2.out", onUpdate: () => iris(st, ap.r, ap.rot) })
          .to(ap, { r: 0.78, rot: Math.PI / 3, duration: 1.5, ease: "expo.inOut", onUpdate: () => iris(st, ap.r, ap.rot), onComplete: () => { st.style.clipPath = "none"; } })
          .to(blur, { px: 0, duration: 1.6, ease: "power2.out", onUpdate: () => { st.style.filter = blur.px > 0.05 ? `blur(${blur.px.toFixed(2)}px)` : ""; } }, "<0.2")
          .call(() => setPlay(true), [], 0.9)
          .to("[data-hud-corner]", { scale: 1, duration: 0.7, stagger: 0.06, ease: "back.out(1.6)" }, 1.2);

        // ---- scroll: overlay clears, lens rises, the machine view takes the frame ----
        const out = gsap.timeline({
          scrollTrigger: {
            trigger: root.current,
            start: "top top",
            end: "bottom bottom",
            scrub: true,
            onUpdate: (self) => { state.current.scroll = self.progress; },
          },
        });
        out.to("[data-hero-overlay]", { autoAlpha: 0, y: -60, ease: "power1.in", duration: 0.25 }, 0)
          .to("[data-hud]", { autoAlpha: 0, duration: 0.2 }, 0.05)
          .fromTo("[data-hero-through]", { autoAlpha: 0, scale: 0.94 }, { autoAlpha: 1, scale: 1, duration: 0.15, ease: "power2.out" }, 0.5)
          .to("[data-hero-through]", { autoAlpha: 0, duration: 0.1 }, 0.82)
          .to("[data-hero-veil]", { autoAlpha: 1, duration: 0.14, ease: "none" }, 0.86);

        return () => {
          tl.kill();
          st.style.clipPath = "";
          st.style.filter = "";
        };
      });
    },
    { scope: root, dependencies: [ready, gl] }
  );

  // ---- intro, part two: once the name exists, detect it, show it to the machine, drop the lens ----
  const onGenerated = useCallback(() => contextSafe(() => {
    measure();
    if (window.matchMedia("(prefers-reduced-motion: reduce)").matches || gl === false) return;
    const conf = { v: 0 };
    const tag = root.current?.querySelector("[data-detect-conf]");
    const split = SplitText.create("[data-hero-split]", { type: "lines,words", mask: "lines" });
    gsap.timeline({ defaults: { ease: "expo.out" } })
      .fromTo("[data-bracket]", { autoAlpha: 0, scale: 1.6 }, { autoAlpha: 1, scale: 1, duration: 0.7, stagger: 0.05 }, 0)
      .fromTo("[data-detect-tag]", { autoAlpha: 0, y: 6 }, { autoAlpha: 1, y: 0, duration: 0.5 }, 0.3)
      .to(conf, { v: 0.99, duration: 1, ease: "power2.out", onUpdate: () => { if (tag) tag.textContent = conf.v.toFixed(2); } }, 0.3)
      .to(state.current, { nameOn: 1, duration: 0.8, ease: "power1.out" }, 0.4)
      .to("[data-bracket], [data-detect-tag]", { autoAlpha: 0, duration: 0.6, ease: "power2.in" }, 2.4)
      .set("[data-hero-split]", { autoAlpha: 1 }, 0.5)
      .from(split.words, { yPercent: 110, duration: 1.1, stagger: 0.035 }, 0.5)
      .to("[data-hero-fade]", { autoAlpha: 1, y: 0, duration: 0.8, stagger: 0.08 }, 0.9)
      .to(state.current, { lens: 1, duration: 0.01 }, 1.2);
  })(), [contextSafe, measure, gl]);

  return (
    <section id="top" ref={root} aria-labelledby="hero-title" className="relative h-[100svh] motion-safe:h-[260svh]">
      <noscript>
        <style>{`[data-name-h1]{visibility:visible!important}`}</style>
      </noscript>
      <div className="sticky top-0 h-[100svh] overflow-hidden bg-[#000]">
        {/* the stage, behind an aperture: the name (DOM) under a transparent WebGL canvas */}
        <div ref={stage} className="absolute inset-0 bg-ink [clip-path:circle(0%)] motion-reduce:[clip-path:none]">
          <div className="shell absolute inset-x-0 top-[19svh] sm:top-[20svh]">
            <DiffusionName
              play={play}
              onGenerated={onGenerated}
              extras={
                <div className="pointer-events-none absolute -inset-x-5 -inset-y-4" aria-hidden>
                  {["left-0 top-0 border-l-2 border-t-2", "right-0 top-0 border-r-2 border-t-2", "left-0 bottom-0 border-l-2 border-b-2", "right-0 bottom-0 border-r-2 border-b-2"].map((c) => (
                    <span key={c} data-bracket className={`invisible absolute size-6 border-signal ${c}`} />
                  ))}
                  <span data-detect-tag className="invisible absolute -top-7 left-0 bg-signal px-2 py-1 font-mono text-[12px] leading-none text-on-signal">
                    mehul_dadhich <span data-detect-conf>0.00</span>
                  </span>
                </div>
              }
            >
              <h1
                id="hero-title"
                data-name-h1
                className="serif invisible text-[clamp(4.2rem,1rem+12vw,12.5rem)] leading-[0.86] tracking-[-0.035em] motion-reduce:visible"
              >
                <span data-line className="block">Mehul</span>
                <span data-line className="block pl-[0.75em] italic">Dadhich</span>
                <span className="sr-only">, {profile.role}</span>
              </h1>
            </DiffusionName>
          </div>
          <div className="pointer-events-none absolute inset-0">
            {gl ? <LensScene state={state} active={active} onReady={onReady} /> : null}
          </div>
        </div>

        {/* viewfinder: corner brackets and readouts */}
        <div data-hud className="pointer-events-none absolute inset-3 sm:inset-5" aria-hidden>
          {["left-0 top-16 border-l border-t", "right-0 top-16 border-r border-t", "left-0 bottom-0 border-l border-b", "right-0 bottom-0 border-r border-b"].map((c, i) => (
            <span key={c} data-hud-corner className={`absolute size-5 border-fg/40 ${c}`} style={{ transformOrigin: `${i % 2 ? "100%" : "0%"} ${i < 2 ? "0%" : "100%"}` }} />
          ))}
          <div data-hero-fade className="invisible absolute right-0 top-20 hidden items-center gap-4 font-mono text-[10.5px] tracking-[0.12em] text-soft uppercase md:flex">
            <span className="flex items-center gap-2"><span className="size-2 rounded-full bg-fg" /> Human view</span>
            <span className="flex items-center gap-2">
              <span className="h-2 w-6 rounded-full bg-[linear-gradient(90deg,var(--depth-0),var(--depth-1),var(--depth-2),var(--depth-3))]" /> Machine view
            </span>
          </div>
        </div>

        {/* the words */}
        <div data-hero-overlay className="pointer-events-none absolute inset-x-0 bottom-0 pb-[max(1.5rem,env(safe-area-inset-bottom))]">
          <div className="shell grid grid-cols-12 items-end gap-x-6 gap-y-6">
            <div data-hero-in className="invisible col-span-12 md:col-span-8 lg:col-span-7">
              <p data-hero-fade className="label mb-4 flex items-center gap-2 text-fg">
                <span className="relative flex size-2" aria-hidden>
                  <span className="absolute inset-0 rounded-full bg-ok opacity-60 motion-safe:animate-ping motion-safe:[animation-duration:2.4s]" />
                  <span className="relative size-2 rounded-full bg-ok" />
                </span>
                Open to AI/ML roles · {profile.location}
              </p>
              <p data-hero-split className="serif text-[clamp(1.6rem,1.1rem+1.9vw,2.9rem)] leading-[1.06] tracking-[-0.02em]">
                AI/ML engineer. I build AI systems and take them <em className="text-signal">past the notebook.</em>
              </p>
              <div data-hero-fade className="pointer-events-auto mt-6 flex flex-wrap items-center gap-1.5 sm:gap-2">
                <button
                  type="button"
                  onClick={() => scrollToId("featured")}
                  className="group flex h-11 items-center gap-1.5 rounded-full bg-fg pl-3.5 pr-3 text-[13.5px] font-medium text-ink transition-transform duration-300 hover:scale-[1.03] active:scale-[0.98] sm:h-12 sm:gap-2 sm:pl-5 sm:pr-4 sm:text-[15px]"
                >
                  See what the model sees
                  <ArrowDown className="size-4 transition-transform duration-300 group-hover:translate-y-0.5" aria-hidden />
                </button>
                <a href={gmailCompose()} target="_blank" rel="noreferrer" aria-label="Email (opens Gmail)" className="grid size-11 place-items-center rounded-full border border-line-strong bg-ink/40 backdrop-blur-sm transition-colors hover:border-fg sm:size-12">
                  <Mail className="size-4" aria-hidden />
                </a>
                <a href={profile.github} target="_blank" rel="noreferrer" aria-label="GitHub" className="grid size-11 place-items-center rounded-full border border-line-strong bg-ink/40 backdrop-blur-sm transition-colors hover:border-fg sm:size-12">
                  <GithubIcon className="size-4" />
                </a>
                <a href={profile.linkedin} target="_blank" rel="noreferrer" aria-label="LinkedIn" className="grid size-11 place-items-center rounded-full border border-line-strong bg-ink/40 backdrop-blur-sm transition-colors hover:border-fg sm:size-12">
                  <LinkedinIcon className="size-4" />
                </a>
              </div>
            </div>
            <p data-hero-fade className="invisible col-span-12 hidden text-right font-mono text-[11px] leading-relaxed tracking-[0.1em] text-soft uppercase md:col-span-4 md:col-start-9 md:block lg:col-span-3 lg:col-start-10" aria-hidden>
              Move the lens to see what the model sees.
              <br />
              Hover the name to disturb it.
              <br />
              Scroll to look through it <span className="inline-block motion-safe:animate-bounce">↓</span>
            </p>
          </div>
        </div>

        {/* mid-transition caption, then the veil that hands over to the next chapter */}
        <p data-hero-through className="pointer-events-none invisible absolute inset-x-0 bottom-[16%] text-center font-mono text-[12px] tracking-[0.3em] text-fg uppercase" aria-hidden>
          Switching to machine view
        </p>
        <div data-hero-veil className="pointer-events-none invisible absolute inset-0 bg-[#05070f]" aria-hidden />
      </div>
    </section>
  );
}
